-- Демо-аптеки: в каждой должны быть ходовые лекарства (раньше набор сдвигался
-- от аптеки к аптеке, и, например, парацетамола не было в трёх аптеках из восьми).
-- Добавляем недостающие позиции; то, что аптека уже завела сама, не трогаем.
-- Список, цены и наличие — как в internal/seed/seed.go (popular, itemPrice, itemInStock):
-- k — номер лекарства в seed.medicines, i — номер аптеки, coef — множитель цены аптеки.
INSERT INTO pharmacy_items (pharmacy_id, medicine_id, price, in_stock)
SELECT p.id, m.id,
       (round(v.base * a.coef * (1 + ((a.i * 7 + v.k * 13) % 11 - 5) / 100.0) / 10) * 10)::int,
       (a.i * 5 + v.k * 3 + 4) % 11 <> 0
FROM (VALUES
    ('Парацетамол', 0, 300),
    ('Ибупрофен', 2, 550),
    ('Нурофен', 3, 1900),
    ('Амоксициллин', 4, 1100),
    ('Азитромицин', 6, 1500),
    ('Омепразол', 8, 900),
    ('Метформин', 10, 1200),
    ('Глюкофаж', 11, 2800),
    ('Лизиноприл', 12, 800),
    ('Амлодипин', 13, 700),
    ('Аторвастатин', 14, 1700),
    ('Цетиризин', 15, 600),
    ('Амброксол', 18, 900),
    ('Ацетилцистеин', 19, 1800),
    ('Дротаверин', 22, 400),
    ('Но-шпа', 23, 1600),
    ('Панкреатин', 24, 700),
    ('Лоперамид', 25, 500),
    ('Диклофенак', 27, 650),
    ('Бисопролол', 29, 1300)
) AS v(name, k, base)
JOIN medicines m ON m.name = v.name
CROSS JOIN (VALUES
    ('apteka1', 0, 1.00),
    ('apteka2', 1, 1.10),
    ('apteka3', 2, 0.90),
    ('apteka4', 3, 1.20),
    ('apteka5', 4, 0.85),
    ('apteka6', 5, 0.95),
    ('apteka7', 6, 1.05),
    ('apteka8', 7, 1.15)
) AS a(login, i, coef)
JOIN pharmacies p ON p.login = a.login
ON CONFLICT (pharmacy_id, medicine_id) DO NOTHING;
